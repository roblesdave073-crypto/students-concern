-- Separate Supabase schema for the GitHub Pages application.
-- Uses Supabase Auth and RLS; it does not alter the original MySQL system.
create table if not exists public.v2_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '', email text not null,
  role text not null default 'student' check (role in ('admin','student','staff')),
  is_active boolean not null default true,
  student_number varchar(50) unique, course varchar(120), year_level varchar(30),
  department_id bigint, position varchar(120),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.v2_departments (
  id bigint generated by default as identity primary key,
  name varchar(120) not null unique, description text, created_at timestamptz not null default now()
);
create table if not exists public.v2_categories (
  id bigint generated by default as identity primary key,
  name varchar(120) not null unique, is_active boolean not null default true,
  created_at timestamptz not null default now()
);
alter table public.v2_profiles drop constraint if exists v2_profiles_department_id_fkey;
alter table public.v2_profiles add constraint v2_profiles_department_id_fkey
  foreign key (department_id) references public.v2_departments(id) on delete set null;

create table if not exists public.v2_complaints (
  id bigint generated by default as identity primary key, tracking_no varchar(32) unique,
  student_id uuid not null references public.v2_profiles(id),
  category_id bigint not null references public.v2_categories(id),
  department_id bigint not null references public.v2_departments(id),
  title varchar(180) not null, description text not null,
  status text not null default 'Pending' check (status in ('Pending','Under Review','Assigned','In Progress','Resolved','Rejected','Reopened')),
  priority text not null default 'Medium' check (priority in ('Low','Medium','High','Urgent')),
  is_anonymous boolean not null default false, rejection_reason text, resolution_details text,
  archived_at timestamptz, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create index if not exists v2_complaints_status_created_idx on public.v2_complaints(status, created_at desc);
create index if not exists v2_complaints_student_idx on public.v2_complaints(student_id, created_at desc);

create table if not exists public.v2_complaint_assignments (
  id bigint generated by default as identity primary key,
  complaint_id bigint not null references public.v2_complaints(id) on delete cascade,
  staff_id uuid not null references public.v2_profiles(id),
  assigned_by uuid not null references public.v2_profiles(id),
  created_at timestamptz not null default now(), unique (complaint_id, staff_id)
);
create table if not exists public.v2_complaint_updates (
  id bigint generated by default as identity primary key,
  complaint_id bigint not null references public.v2_complaints(id) on delete cascade,
  user_id uuid not null references public.v2_profiles(id), previous_status varchar(30),
  new_status varchar(30), message text not null, is_internal boolean not null default false,
  created_at timestamptz not null default now()
);
create table if not exists public.v2_notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.v2_profiles(id) on delete cascade,
  complaint_id bigint references public.v2_complaints(id) on delete set null,
  title varchar(180) not null, message text not null, is_read boolean not null default false,
  created_at timestamptz not null default now()
);
create table if not exists public.v2_feedback (
  id bigint generated by default as identity primary key,
  complaint_id bigint not null unique references public.v2_complaints(id) on delete cascade,
  student_id uuid not null references public.v2_profiles(id),
  rating smallint not null check (rating between 1 and 5), comments text,
  created_at timestamptz not null default now()
);
create table if not exists public.v2_activity_logs (
  id bigint generated by default as identity primary key,
  user_id uuid references public.v2_profiles(id) on delete set null,
  complaint_id bigint references public.v2_complaints(id) on delete set null,
  action varchar(255) not null, created_at timestamptz not null default now()
);
create table if not exists public.v2_app_settings (
  setting_key varchar(100) primary key, setting_value text not null,
  updated_at timestamptz not null default now()
);

create or replace function public.v2_touch_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin new.updated_at := now(); return new; end;
$$;
drop trigger if exists v2_profiles_touch on public.v2_profiles;
create trigger v2_profiles_touch before update on public.v2_profiles
for each row execute function public.v2_touch_updated_at();
drop trigger if exists v2_complaints_touch on public.v2_complaints;
create trigger v2_complaints_touch before update on public.v2_complaints
for each row execute function public.v2_touch_updated_at();
drop trigger if exists v2_settings_touch on public.v2_app_settings;
create trigger v2_settings_touch before update on public.v2_app_settings
for each row execute function public.v2_touch_updated_at();

create or replace function public.v2_current_role()
returns text language sql stable security definer set search_path = '' as $$
  select role from public.v2_profiles where id = (select auth.uid())
$$;
create or replace function public.v2_is_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce(public.v2_current_role() = 'admin', false)
$$;
create or replace function public.v2_is_assigned(target_id bigint)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.v2_complaint_assignments a
    where a.complaint_id = target_id and a.staff_id = (select auth.uid()))
$$;

create or replace function public.v2_on_signup()
returns trigger language plpgsql security definer set search_path = '' as $$
declare requested_role text;
begin
  requested_role := case when new.raw_user_meta_data ->> 'requested_role' = 'staff' then 'staff' else 'student' end;
  insert into public.v2_profiles(id,full_name,email,role,is_active,student_number,course,year_level,department_id,position)
  values(new.id,coalesce(new.raw_user_meta_data ->> 'full_name',''),coalesce(new.email,''),requested_role,
    requested_role = 'student',nullif(new.raw_user_meta_data ->> 'student_number',''),
    nullif(new.raw_user_meta_data ->> 'course',''),nullif(new.raw_user_meta_data ->> 'year_level',''),
    nullif(new.raw_user_meta_data ->> 'department_id','')::bigint,nullif(new.raw_user_meta_data ->> 'position',''));
  return new;
end;
$$;
drop trigger if exists v2_auth_signup on auth.users;
create trigger v2_auth_signup after insert on auth.users
for each row execute function public.v2_on_signup();

create or replace function public.v2_protect_profile()
returns trigger language plpgsql set search_path = '' as $$
begin
  if (select auth.uid()) is not null and not public.v2_is_admin()
     and (new.id is distinct from old.id or new.created_at is distinct from old.created_at
       or new.role is distinct from old.role or new.is_active is distinct from old.is_active
       or new.email is distinct from old.email or new.department_id is distinct from old.department_id) then
    raise exception 'Only an administrator can change this profile field.';
  end if;
  return new;
end;
$$;
drop trigger if exists v2_profile_guard on public.v2_profiles;
create trigger v2_profile_guard before update on public.v2_profiles
for each row execute function public.v2_protect_profile();

create or replace function public.v2_protect_complaint()
returns trigger language plpgsql set search_path = '' as $$
begin
  if (select auth.uid()) is null or public.v2_is_admin() then return new; end if;
  if public.v2_is_assigned(old.id) then
    if new.status is distinct from old.status and new.status not in ('Under Review','In Progress','Resolved') then
      raise exception 'Assigned staff can move a concern to Under Review, In Progress, or Resolved.';
    end if;
    if new.id is distinct from old.id or new.created_at is distinct from old.created_at
       or new.student_id is distinct from old.student_id or new.category_id is distinct from old.category_id
       or new.department_id is distinct from old.department_id or new.title is distinct from old.title
       or new.description is distinct from old.description or new.is_anonymous is distinct from old.is_anonymous
       or new.tracking_no is distinct from old.tracking_no or new.archived_at is distinct from old.archived_at
       or new.rejection_reason is distinct from old.rejection_reason then
      raise exception 'Assigned staff can update status and resolution details only.';
    end if;
    return new;
  end if;
  if old.student_id = (select auth.uid()) and old.status = 'Resolved' and new.status = 'Reopened'
     and new.id is not distinct from old.id
     and new.created_at is not distinct from old.created_at
     and new.student_id is not distinct from old.student_id
     and new.category_id is not distinct from old.category_id
     and new.department_id is not distinct from old.department_id
     and new.title is not distinct from old.title
     and new.description is not distinct from old.description
     and new.priority is not distinct from old.priority
     and new.is_anonymous is not distinct from old.is_anonymous
     and new.tracking_no is not distinct from old.tracking_no
     and new.rejection_reason is not distinct from old.rejection_reason
     and new.resolution_details is not distinct from old.resolution_details
     and new.archived_at is not distinct from old.archived_at then
    return new;
  end if;
  raise exception 'You cannot edit this concern.';
end;
$$;
drop trigger if exists v2_complaint_guard on public.v2_complaints;
create trigger v2_complaint_guard before update on public.v2_complaints
for each row execute function public.v2_protect_complaint();

